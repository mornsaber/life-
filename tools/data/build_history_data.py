states = {}
for _, r in g.iterrows():
    states.setdefault(int(r.gwcode), {'name': str(r.statename), 'spans': []})['spans'].append([int(r.s), int(r.e) if int(r.e) < 2017 else None])
sovereign = {cc: [sp for c in codes if c in states for sp in states[c]['spans']] for cc, codes in GW.items() if codes[0] in states}
sovereign = {cc: sorted(v) for cc, v in sovereign.items()}
write('states.js', 'The state system since 1816: every independent state with the years it existed (Gleditsch & Ward), and the years each of our countries was sovereign.',
      'Gleditsch & Ward (1999) list of independent states, via the peacesciencer R package (svmiller/peacesciencer)',
      {'STATES': {str(k): v for k, v in states.items()}, 'SOVEREIGN_YEARS': sovereign})

# ---------------------------------------------------------------- wars
names = {int(float(r['id'])): r['name'] for r in csv.DictReader(open(EXT + 'correlates-of-war/data/processed/war.csv'))}
wi = rdata.read_rda(EXT + 'peacesciencer/data/cow_war_inter.rda')['cow_war_inter']
wars = {}
for _, r in wi.iterrows():
    n = int(r.warnum)
    w = wars.setdefault(n, {'name': names.get(n, f'War {n}'), 'kind': 'inter', 'from': 9999, 'to': 0, 'a': set(), 'b': set(), 'deaths': {}})
    y = int(r.year); w['from'] = min(w['from'], y); w['to'] = max(w['to'], y)
    c1 = cow_cc(r.ccode1)
    if c1:
        (w['a'] if r.sidea1 == 1 else w['b']).add(c1)
        w['deaths'][c1] = max(w['deaths'].get(c1, 0), int(r.batdeath1) if not math.isnan(r.batdeath1) and r.batdeath1 > 0 else 0)
        if r.outcome1 == 1: w.setdefault('won', set()).add(c1)
wa = rdata.read_rda(EXT + 'peacesciencer/data/cow_war_intra.rda')['cow_war_intra']
for _, r in wa.iterrows():
    cc = cow_cc(r.ccodea) if r.ccodea > 0 else None
    if not cc: continue
    n = int(r.warnum)
    w = wars.setdefault(n, {'name': str(r.warname), 'kind': 'civil', 'from': 9999, 'to': 0, 'a': set(), 'b': set(), 'deaths': {}, 'rebels': str(r.sideb)})
    y = int(r.year); w['from'] = min(w['from'], y); w['to'] = max(w['to'], y)
    w['a'].add(cc)
    d = int((0 if math.isnan(r.sideadeaths) or r.sideadeaths < 0 else r.sideadeaths) + (0 if math.isnan(r.sidebdeaths) or r.sidebdeaths < 0 else r.sidebdeaths))
    w['deaths'][cc] = max(w['deaths'].get(cc, 0), d)
out = []
for n, w in sorted(wars.items(), key=lambda kv: (kv[1]['from'], kv[0])):
    if not (w['a'] | w['b']): continue
    row = {'id': n, 'name': w['name'], 'kind': w['kind'], 'from': w['from'], 'to': w['to'], 'a': sorted(w['a']), 'b': sorted(w['b']), 'deaths': w['deaths']}
    if w.get('won'): row['won'] = sorted(w['won'])
    if w.get('rebels'): row['rebels'] = w['rebels']
    out.append(row)
write('wars.js', 'Wars since 1816 that our countries fought: inter-state wars (sides a and b) and civil wars (the government on side a), with battle deaths by country.',
      'Correlates of War Inter-State and Intra-State War Data v4 (Sarkees & Wayman 2010), via peacesciencer; war names from jenna-jordan/correlates-of-war', {'WARS': out})

# ---------------------------------------------------------------- demography
OWID_NAME = {v: k for k, v in NAMES.items()}
OWID_NAME.update({'Turkey': 'TR', "Cote d'Ivoire": 'CI', 'Democratic Republic of Congo': 'CD', 'Bahamas': 'BS', 'Czechia': None, 'Micronesia (country)': None})
mad = pd.read_csv(OWID + 'Maddison Project Database 2020 (Bolt and van Zanden (2020))/Maddison Project Database 2020 (Bolt and van Zanden (2020)).csv')
le = pd.read_csv(OWID + 'Life expectancy - Riley (2005), Clio Infra (2015), and UN (2019)/Life expectancy - Riley (2005), Clio Infra (2015), and UN (2019).csv')
YEARS = list(range(1800, 2021, 5))
def series(df, entity, col):
    d = df[(df.Entity == entity) & df[col].notna()][['Year', col]]
    return {int(y): float(v) for y, v in zip(d.Year, d[col])}
def at(s, y):
    """Value in year y, interpolating between observations; None outside them."""
    if not s: return None
    ys = sorted(s)
    if y < ys[0] or y > ys[-1]: return None
    if y in s: return s[y]
    lo = max(k for k in ys if k < y); hi = min(k for k in ys if k > y)
    return s[lo] + (s[hi] - s[lo]) * (y - lo) / (hi - lo)
demo = {}
for entity in sorted(set(mad.Entity) | set(le.Entity)):
    cc = OWID_NAME.get(entity)
    if not cc or cc not in OURS: continue
    gdp, pop, life = series(mad, entity, 'GDP per capita'), series(mad, entity, 'Population'), series(le, entity, 'Life expectancy')
    row = {'gdp': [], 'pop': [], 'life': []}
    for y in YEARS:
        a, b, c = at(gdp, y), at(pop, y), at(life, y)
        row['gdp'].append(None if a is None else round(a))
        row['pop'].append(None if b is None else round(b / 1000))
        row['life'].append(None if c is None else round(c, 1))
    demo[cc] = row
write('demography.js', 'Every five years from 1800 to 2020: GDP per head (2011 US dollars), population (thousands) and life expectancy at birth, interpolated between observations.',
      'Maddison Project Database 2020 (Bolt & van Zanden, CC BY 4.0); life expectancy from Riley (2005), Clio Infra (2015) and the UN (2019), compiled by Our World in Data (CC BY 4.0)',
      {'DEMOGRAPHY_YEARS': YEARS, 'DEMOGRAPHY': demo})

# ---------------------------------------------------------------- names
b = rdata.read_rda(EXT + 'babynames/data/babynames.rda')['babynames']
b['decade'] = (b.year // 10 * 10).astype(int)
top = {}
for (dec, sex), grp in b.groupby(['decade', 'sex']):
    t = grp.groupby('name')['n'].sum().sort_values(ascending=False).head(60)
    top.setdefault(str(dec), {})['male' if sex == 'M' else 'female'] = list(t.index)
write('names.js', 'The most popular US baby names of each decade, 1880s–2010s (60 per sex, most popular first).',
      'US Social Security Administration baby names (public domain), via the babynames R package (hadley/babynames)', {'US_NAMES_BY_DECADE': top})
print('done')
