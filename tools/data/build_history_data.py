CODE_TO_CC = {}
for cc, codes in GW.items():
    for c in codes:
        CODE_TO_CC.setdefault(c, cc)
# COW's own codes where they differ.
COW_EXTRA = {345: 'RS', 340: 'RS', 315: 'CZ', 316: 'CZ', 317: 'SK', 310: 'HU', 680: 'YE', 679: 'YE', 817: 'VN', 731: 'KP', 265: 'DE', 260: 'DE'}
def cow_cc(code):
    code = int(code)
    if code in COW_EXTRA: return COW_EXTRA[code]
    return CODE_TO_CC.get(code)

def js_header(title, sources):
    return f"/**\n * {title}\n * Generated by the data build from open datasets: {sources}.\n * See SOURCES.md in this folder. Do not edit by hand.\n */\n"

def write(name, title, sources, exports):
    body = js_header(title, sources)
    for k, v in exports.items():
        body += f"export const {k} = {json.dumps(v, separators=(',', ':'), ensure_ascii=False)};\n"
    open(OUT + name, 'w').write(body)
    print(name, len(body) // 1024, 'KB')

# ---------------------------------------------------------------- regimes
an = rdata.read_rda(EXT + 'democracyData/data/anckar.rda')['anckar']
CAT = {'Parliamentarism': 'parl', 'Presidentialism': 'pres', 'Semi-presidentialism': 'semi', 'Absolute monarchy': 'absmon', 'Semi-monarchy': 'semimon',
       'Monarchic oligarchy': 'monolig', 'Other oligarchy': 'olig', 'Military rule': 'mil', 'Personalist rule': 'pers', 'Single-party rule': 'oneparty',
       'Multi-party authoritarian rule': 'multiauth'}
regimes = {}
for cc, codes in GW.items():
    rows = an[an['GWn'].isin(codes)].copy()
    if rows.empty: continue
    rows['pri'] = rows['GWn'].map(lambda c: codes.index(int(c)))
    rows = rows.sort_values(['year', 'pri']).drop_duplicates('year')
    runs = []
    for _, r in rows.iterrows():
        cat = CAT.get(str(r['regimenarrowcat']))
        if not cat: continue
        num = lambda v: 0 if v is None or (isinstance(v, float) and math.isnan(v)) else int(v)
        key = [cat, num(r['democracy']), num(r['monarchy'])]
        if not runs or runs[-1][1:] != key: runs.append([int(r['year'])] + key)
    regimes[cc] = runs
write('regimes.js', 'Form of government by year, 1800–2024: [from year, regime, democracy (0/1), monarchy (0/1)], a new row at each change.',
      'Anckar & Fredriksson (2019), "Classifying political regimes 1800–2016", via the democracyData R package (xmarquez/democracyData)', {'REGIME_YEARS': regimes})

# ---------------------------------------------------------------- states (splits & mergers)
g = rdata.read_rda(EXT + 'peacesciencer/data/gw_states.rda')['gw_states']
g['s'] = pd.to_datetime(g.startdate, unit='D').dt.year
